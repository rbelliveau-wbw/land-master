import fs from 'node:fs';

// Field limits come from the committed Creator catalog, not HTML input attributes.
const source = 'creator/exports/Land_Master_2026-11-02-catalog.ds';
const ds = fs.readFileSync(source, 'utf8').replace(/\r/g, '');
const forms = ['Add_Pro_Forma','LOI_Worksheet','Builder','Property','Land_Installments','Proforma_Item','Construction_Curve','Lot_Mix_Row','Proforma_Phase'];
const rules = {};
for (const form of forms) {
  const start = ds.indexOf('\t\tform '+form+'\n');
  if (start < 0) throw Error('Missing form '+form);
  const end = ds.indexOf('\n\t\tform ', start+1);
  rules[form] = {};
  for (const match of ds.slice(start,end).matchAll(/^\t\t\t([^\n]+)\n\t\t\t\(\n([\s\S]*?)^\t\t\t\)/gm)) {
    const key = match[1].trim().split(/\s+/).at(-1), body = match[2];
    const type = body.match(/\btype\s*=\s*([^\n]+)/)?.[1].trim();
    if (!['text','textarea','email','phonenumber','number','decimal','USD','percentage','url','date','picklist'].includes(type)) continue;
    if (type === 'picklist' && !body.match(/values\s*=\s*\{/)) continue;
    const rule = {type, label:body.match(/displayname\s*=\s*"([^"]+)"/)?.[1] || key.replace(/_/g,' ')};
    const max = body.match(/\bmaxchar\s*=\s*(\d+)/)?.[1];
    if (max) rule.max = Number(max);
    if (type === 'text') rule.max ||= 255;
    if (type === 'email') rule.max ||= 80;
    if (type === 'number') rule.max ||= 19;
    // Preserve the existing decimal-capacity migration and precision contract.
    // Old export maxchar values predate that migration; never restore those limits.
    if (['decimal','USD','percentage'].includes(type)) rule.max = 19;
    const choices = body.match(/values\s*=\s*(\{[^\n]+\})/)?.[1];
    if (choices) rule.choices = [...choices.matchAll(/"([^"]*)"/g)].map(m=>m[1]);
    rules[form][key] = rule;
  }
}
// The existing API intentionally restricts Seller names to 50 characters.
rules.Builder.Builder_Name.max = 50;
// These choices are supported by the current widget and server contract.
delete rules.Add_Pro_Forma.Construction_Length.choices;
delete rules.Construction_Curve.Cost_Curve.choices;
rules.Proforma_Item.Cost_Application.choices.push('Specific Months');
export const output = '// Generated by scripts/build-proforma-input-rules.mjs from '+source+'\nwindow.LMPFInputRules='+JSON.stringify(rules)+';\n';
const target = 'widgets/proforma-manager/src/app/pf-input-rules.js';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target,'utf8') !== output) throw Error('Regenerate Pro Forma field rules.');
} else if(process.argv[1]?.endsWith('build-proforma-input-rules.mjs')) fs.writeFileSync(target,output);
