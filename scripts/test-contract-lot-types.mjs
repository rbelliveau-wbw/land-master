import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('widgets/contract-management/src/app/widget.html','utf8');
function fn(name){const start=source.indexOf('function '+name+'(');assert.ok(start>=0,name);const end=source.indexOf('\n',start);return source.slice(start,source.slice(start,end).trim().endsWith('}')?end:source.indexOf('\n}',start)+2);}
const master={ID:'1',Contract_Type:'Lot (Master)',Builder:{ID:'10'},Contract_Name:'Master A'};
const child={ID:'2',Contract_Type:'Lot (Amendment)',Builder:{ID:'10'},Parent_Contract:{ID:'1'},Contract_Name:'Amendment A',Subdivision1:[{ID:'20'}]};
const ctx={S:{contracts:[child,master,{ID:'3',Contract_Type:'Lot (Master)',Builder:{ID:'11'}},{ID:'4',Contract_Type:'Amendment',Builder:{ID:'10'}},{ID:'5',Contract_Type:'Lot',Builder:{ID:'10'},Contract_Name:'Legacy'}]},LOT_TAKEDOWN_FIELDS:[['Number_of_Lots','Lot Total']],CFG:{reports:{contracts:'contracts'}},esc:String,findContract:id=>ctx.S.contracts.find(c=>c.ID===id),sdkGetAll:async()=>[master]};
vm.createContext(ctx);
for(const name of ['asList','lookupId','displayValue','lotTypeLabel','isLotType','isLotContract','isLotAmendment','lotGroup','lotHasScope','lotParentOptions','lotParentValid','lotHierarchyLabel','lotHierarchyOrder','lotCompletionBlockers','lotValidateParent'])vm.runInContext(fn(name),ctx);
const plain=v=>JSON.parse(JSON.stringify(v));
assert.equal(ctx.lotTypeLabel('Lot'),'Lot (Master)');
assert.equal(ctx.lotGroup(master),'Lot');assert.equal(ctx.lotGroup(child),'Lot');
assert.deepEqual(plain(ctx.lotParentOptions('10','2')).map(o=>o.v),['5','1']);
assert.equal(ctx.lotParentOptions('', '2').length,0);
assert.equal(ctx.lotParentValid({builder:'10',parent:''}),true);
assert.equal(ctx.lotParentValid({builder:'10',parent:'3'}),false);
assert.deepEqual(plain(ctx.lotHierarchyOrder([child,master])).map(c=>c.ID),['1','2']);
assert.deepEqual(plain(ctx.lotHierarchyOrder([child])).map(c=>c.ID),['2'],'filtered-out parent does not hide the child');
assert.match(ctx.lotHierarchyLabel(child),/Amendment.*Master A/);
assert.deepEqual(plain(ctx.lotCompletionBlockers(master)),[],'Master without scope can complete');
assert.deepEqual(plain(ctx.lotCompletionBlockers({...child,Subdivision1:[]})),['Subdivision']);
assert.deepEqual(plain(ctx.lotCompletionBlockers(child)),['Lot Total']);
await ctx.lotValidateParent({builder:'10',parent:''},'2');
await ctx.lotValidateParent({builder:'10',parent:'1'},'2');
ctx.sdkGetAll=async()=>[{...master,Builder:{ID:'11'}}];
await assert.rejects(ctx.lotValidateParent({builder:'10',parent:'1'},'2'),/same builder/,'fresh read prevents a stale parent selection');
assert.match(source,/Subdivision.*optional/);
assert.match(source,/if\(isLotAmendment\(v.type\)&&!v.sub.length\)/);
console.log('Master / Amendment scope, optional parent, matching counterparty, hierarchy and completion checks passed.');
