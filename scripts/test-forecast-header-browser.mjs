import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {forecastSummaryFixture} from './test-forecast-compact-summary.mjs';

const {chromium}=createRequire(import.meta.url)('playwright');
const app='widgets/forecast-manager/src/app/',output='tmp/forecast-header';
fs.mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
  const page=await browser.newPage({viewport:{width:1440,height:950}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.setContent('<!doctype html><title>Forecast header fixture</title><main class="main"><section id="host" class="compact-summary"></section></main>');
  await page.addStyleTag({content:fs.readFileSync(app+'forecast.css','utf8')+'\n'+fs.readFileSync(app+'forecast-header.css','utf8')+'\n'+fs.readFileSync(app+'number-transitions.css','utf8')});
  await page.addScriptTag({content:fs.readFileSync(app+'number-transitions.js','utf8')});
  await page.addScriptTag({content:fs.readFileSync(app+'forecast-summary.js','utf8')});
  const html=forecastSummaryFixture(),inventory={territory:'North Austin',counts:{Total:148,Sold:73,Scheduled:5,Contracted:1,Open:69},builders:[]};
  const overview={version:1,projectStatus:'Awaiting CONST',territory:'North Austin',firstSoldDate:'2025-12-30',lastSoldDate:'2026-04-18',firstForecastDate:'2026-03-01',finalForecastDate:'2029-06-01',soldOut:false,projectsLots:200,lmLots:148,displayTotalLabel:'Sold + Forecast',displayTotal:376,projectsDifference:-176,lmDifference:-228};
  const render=async(data=overview)=>page.evaluate(({html,inventory,data})=>ForecastSummary.render(html,document.getElementById('host'),inventory,'subdivision-1',data),{html,inventory,data});
  assert.equal(await render(),true);
  const field=key=>page.locator('[data-overview-field="'+key+'"] .fs-header-value');
  assert.equal(await field('firstDate').innerText(),'12/30/2025');
  assert.equal(await field('lastSoldDate').innerText(),'04/18/2026');
  assert.equal(await field('finalDate').innerText(),'06/01/2029');
  assert.equal(await field('soldForecast').innerText(),'376');
  assert.equal(await field('projectsLots').innerText(),'200');
  assert.equal(await field('lmLots').innerText(),'148');
  assert.equal(await page.locator('[data-overview-difference="projectsLots"] .number-push-value').innerText(),'-176');
  assert.equal(await page.locator('[data-overview-difference="lmLots"] .number-push-value').innerText(),'-228');
  assert.equal(await page.locator('.fs-project-status').innerText(),'Awaiting CONST');
  assert.match(await page.locator('.fs-meta').innerText(),/TR05/);
  assert.equal(await page.locator('.fs-fact--territory dt').innerText(),'Territory');
  assert.equal(await page.locator('.fs-territory').innerText(),'North Austin');
  assert.equal(await page.locator('[data-native-label="County"]').count(),1);
  assert.equal(await page.locator('[data-native-label="Last Sold Date"]').count(),1,'stored native date remains mapped once');
  assert.equal(await page.locator('.fs-card').count(),3,'all native schedules remain');
  const stableKey=await field('soldForecast').locator('[data-number-key]').getAttribute('data-number-key');
  for(const width of [1280,1440,2308]){
    await page.setViewportSize({width,height:950});
    const geometry=await page.evaluate(()=>{
      const box=node=>node.getBoundingClientRect(),head=box(document.querySelector('.fs-title-head'));
      const fields=[...document.querySelectorAll('.fs-header-field')].map(node=>({field:box(node),value:box(node.querySelector('.fs-header-value')),overflow:node.querySelector('.fs-header-value').scrollWidth-node.querySelector('.fs-header-value').clientWidth,labelOverflow:node.querySelector('.fs-header-label').scrollWidth-node.querySelector('.fs-header-label').clientWidth}));
      const check=box(document.querySelector('.fs-sold-check')),svg=box(document.querySelector('.fs-sold-check svg'));
      return {overflow:document.body.scrollWidth-innerWidth,fields:fields.map(({field,value,overflow,labelOverflow})=>({left:field.left,right:field.right,valueRight:value.right,top:field.top,bottom:field.bottom,overflow,labelOverflow})),headRight:head.right,headBottom:head.bottom,checkError:Math.abs(check.left+check.width/2-svg.left-svg.width/2)+Math.abs(check.top+check.height/2-svg.top-svg.height/2)};
    });
    assert.ok(geometry.overflow<=1,'desktop viewport contains the header');
    assert.ok(geometry.fields.every(field=>field.right<=geometry.headRight+1&&field.valueRight<=geometry.headRight+1&&field.bottom<=geometry.headBottom+1),'every header field fits inside the blue bar');
    assert.ok(geometry.fields.every(field=>field.overflow<=1&&field.labelOverflow<=1),'labels and formatted values fit their own slots');
    assert.ok(geometry.fields.slice(1).every((field,index)=>field.left>=geometry.fields[index].right-1),'header fields do not overlap');
    assert.ok(geometry.checkError<1,'green actual-sale icon is centered');
    await page.screenshot({path:path.join(output,'header-'+width+'.png')});
  }
  await page.evaluate(()=>document.querySelector('.fs-disclosure').open=false);
  await render({...overview,displayTotal:380,projectsDifference:-180,lmDifference:-232});
  assert.equal(await page.locator('.fs-disclosure').getAttribute('open'),null,'refresh preserves the collapsed summary');
  assert.equal(await field('soldForecast').locator('[data-number-key]').getAttribute('data-number-key'),stableKey);
  assert.equal(await field('soldForecast').locator('[data-number-key]').getAttribute('data-number-value'),'380');
  await page.emulateMedia({reducedMotion:'reduce'});
  await render({...overview,firstSoldDate:'',lastSoldDate:'',lmLots:0,lmDifference:-376});
  assert.equal(await field('firstDate').innerText(),'03/01/2026');
  assert.equal(await page.locator('.fs-sold-check').count(),0,'forecast date has no Sold check');
  assert.equal(await field('lastSoldDate').innerText(),'—');
  assert.equal(await field('lmLots').innerText(),'No LM lots');
  assert.equal(await page.locator('[data-overview-difference="lmLots"]').count(),0,'no arithmetic for absent Land Master lots');
  await page.setViewportSize({width:1280,height:950});
  const noLotsGeometry=await page.evaluate(()=>{const node=document.querySelector('[data-overview-field="lmLots"] .fs-header-value');return {overflow:node.scrollWidth-node.clientWidth,pageOverflow:document.body.scrollWidth-innerWidth};});
  assert.ok(noLotsGeometry.overflow<=1&&noLotsGeometry.pageOverflow<=1,'No LM lots stays contained at1280px');
  await render({...overview,soldOut:true});
  assert.equal(await field('finalDate').innerText(),'04/18/2026','sold out uses final actual date');
  assert.equal(await render(null),true,'old backend remains supported');
  assert.equal(await field('firstDate').innerText(),'—');assert.equal(await field('finalDate').innerText(),'—');assert.equal(await field('soldForecast').innerText(),'—');
  assert.equal(await field('projectsLots').innerText(),'148','native Residential count remains available');
  assert.equal(await field('lmLots').innerText(),'148','existing all-lot inventory remains available');
  assert.equal(await field('lastSoldDate').innerText(),'08/06/2026','stored native Last Sold remains a fallback');
  assert.equal(await page.locator('.fs-project-status').innerText(),'Completed','native summary fallback already uses Projects Status');
  await render({...overview,projectStatus:'<img src=x onerror=bad>',territory:'<script>bad</script>'});
  assert.equal(await page.locator('#host img,#host script').count(),0,'metadata is passive text');
  assert.deepEqual(errors,[]);
  console.log('PASS blue-header dates, all-year counts/differences, current native metadata fallback, zero/missing distinction, safe text, centered check, desktop geometry, retained disclosure and stable numeric identities.');
}finally{await browser.close();}
