import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import './test-po-item-picker.mjs';
import './test-po-summary.mjs';
import './test-po-entry.mjs';
import './test-po-date-picker.mjs';
const ctx=vm.createContext({});
vm.runInContext(await readFile(new URL('../widgets/budget-manager/src/app/po-domain.js',import.meta.url),'utf8'),ctx);
const PO=ctx.LMPO;
const line={key:'line-one',budgetItemId:'9007199254740993',description:'Roadwork',uom:'LF',costCode:'C_SH01-3225-5',costElement:'5',pricingMode:'Calculated',quantity:'1.005',unitPrice:'1.00',finalAmount:'1.01'};
const payload={budgetId:'9007199254740994',vendorId:'9007199254740995',amount:'2.02',lines:[line,{...line,key:'line-two'}]};
assert.equal(PO.multiply('1.005','1.00'),'1.01');
assert.equal(PO.multiply('3','0.10'),'0.30');
assert.equal(PO.currency(PO.money('9999999999999.99')),'9999999999999.99');
assert.throws(()=>PO.money('10000000000000.00'),/16/);
assert.throws(()=>PO.money('0.001'),/two/);
assert.throws(()=>PO.money(0.1),/string/);
assert.equal(PO.validate(payload,true).grouped[line.budgetItemId],202n);
assert.equal(PO.validate(payload,true).budgetModificationId,null);
assert.equal(PO.validate({...payload,budgetModificationId:'9007199254740996'},true).budgetModificationId,'9007199254740996');
assert.throws(()=>PO.validate({...payload,budgetModificationId:9007199254740996},true),/modification/i);
assert.throws(()=>PO.validate({...payload,amount:'2.01'},true),/exactly/);
assert.equal(PO.validate({...payload,amount:'2.01'},false).total,'2.02');
assert.throws(()=>PO.validate({...payload,budgetId:9007199254740994},false),/Phase/);
const manual=PO.override(line,'1.01');
assert.equal(manual.quantity,null); assert.equal(manual.unitPrice,null);
PO.validate({...payload,lines:[manual,{...manual,key:'line-two'}]},true);
assert.throws(()=>PO.validate({...payload,lines:[{...manual,quantity:'0'}]},false),/true null/);
const reset=PO.calculated(manual);
assert.equal(reset.quantity,null); assert.equal(reset.unitPrice,null); assert.equal(reset.finalAmount,null);
assert.throws(()=>PO.validate({...payload,lines:[reset]},false),/string/);
assert.throws(()=>PO.validate({...payload,lines:[{...line,costElement:'6'}]},false),/1–5/);
assert.throws(()=>PO.validate({...payload,lines:[line,line]},false),/unique/);
const headers=[{ID:'10',budgetId:payload.budgetId,budgetItemId:line.budgetItemId,amount:'5.00',revision:'',status:''},{ID:'11',budgetId:payload.budgetId,amount:'100.00',status:'Draft'}, {ID:'12',budgetId:payload.budgetId,amount:'2.02',status:'Submitted',revision:'op-three',lineCount:2}];
const committedLines=payload.lines.map(x=>({...x,poId:'12',revision:'op-three'}));
assert.equal(PO.commitments(headers,committedLines,payload.budgetId)[line.budgetItemId],702n);
assert.throws(()=>PO.commitments(headers,committedLines.slice(0,1),payload.budgetId),/incomplete/);
assert.throws(()=>PO.commitments([...headers,headers[0]],committedLines,payload.budgetId),/duplicate/);
assert.throws(()=>PO.commitments(headers,[...committedLines,{...committedLines[0]}],payload.budgetId),/incomplete/);
assert.throws(()=>PO.commitments(headers,committedLines.map(x=>({...x,finalAmount:'1.00'})),payload.budgetId),/allocation/);
assert.throws(()=>PO.commitments(headers,committedLines.map(x=>({...x,budgetItemId:1001})),payload.budgetId),/identity/);
assert.throws(()=>PO.commitments(headers.map(x=>x.ID==='10'?{...x,budgetItemId:1001}:x),committedLines,payload.budgetId),/Legacy/);
assert.throws(()=>PO.commitments(headers,committedLines.map(x=>({...x,finalAmount:'0.00'})),payload.budgetId),/allocation/);
assert.equal(PO.costCode('SH01','3225','5'),'C_SH01-3225-5');
assert.equal(PO.costCode('','3225','5'),'');
assert.deepEqual(Array.from(PO.uoms),['CY','EA','LB','LF','LOTS','LS','S','SET','SF','SY','TN','VF','WK']);
for(const uom of ['ACRE','LOT','TON','TONS',''])assert.throws(()=>PO.validate({...payload,lines:[{...line,uom}]},false),/UOM/);
const zero={...line,key:'no-charge',unitPrice:'0.00',finalAmount:'0.00'};
assert.equal(PO.validate({...payload,amount:'1.01',lines:[line,zero]},true).total,'1.01');
assert.equal(PO.validate({...payload,amount:'101.00',lines:Array.from({length:100},(_,i)=>({...line,key:'row-'+i}))},true).lines.length,100);
assert.throws(()=>PO.validate({...payload,lines:Array.from({length:101},(_,i)=>({...line,key:'row-'+i}))},false),/1–100/);
const balances=[{budgetItemId:line.budgetItemId,availableCents:'100',pendingModificationCents:'50'}];
const allocation=PO.allocations(payload.lines,balances,[],[])[0];
assert.equal(allocation.allocated,202n);assert.equal(allocation.remaining,-102n);assert.equal(allocation.shortfall,52n);
const own=PO.allocations(payload.lines,balances,payload.lines,[{budgetItemId:line.budgetItemId,amount:'0.50',status:'Rejected'}])[0];
assert.equal(own.available,302n);assert.equal(own.pending,0n);assert.equal(own.shortfall,0n);
console.log('Purchase order exact decimals, pricing nulls, grouping, draft/submit and legacy commitment tests passed.');

const copied=PO.duplicate({...line,ID:'native-child',poId:'parent',revision:'saved-revision'},'new-line');
assert.equal(copied.key,'new-line');
for(const field of ['ID','poId','revision'])assert.equal(field in copied,false,'Never copy persisted '+field);
for(const field of ['budgetItemId','description','uom','costElement','pricingMode','quantity','unitPrice','finalAmount','costCode'])assert.equal(copied[field],line[field]);
const manualCopy=PO.duplicate(PO.override(line,'9.99'),'manual-copy');
assert.equal(manualCopy.quantity,null);assert.equal(manualCopy.unitPrice,null);assert.equal(manualCopy.finalAmount,'9.99');
console.log('PO duplicate: all entry fields preserved, manual nulls retained, native identities stripped.');
