import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={module:{exports:{}},Intl,Date};
vm.runInNewContext(fs.readFileSync('widgets/proforma-manager/src/app/comments.js','utf8'),context);
const c=context.module.exports.PFComments;
const row={Added_User:'alice',User:'alice',Added_Time:'15-Sep-2026 08:00:00',Author_Name:'Alice Bell',Deleted:false};
const created=Date.parse('2026-09-15T13:00:00Z');
assert.equal(c.timestamp(row.Added_Time),created);
assert.equal(c.timestamp('15-Jan-2026 08:00:00'),Date.parse('2026-01-15T14:00:00Z'));
assert.equal(c.author(row,[]),'Alice Bell');
assert.equal(c.author({...row,Author_Name:''},[]),'alice');
assert.equal(c.author(row,[{email:'alice',Full_Name:'Alice Updated'}]),'Alice Updated');
assert.equal(c.canChange(row,'alice',created+86400000-1),true);
assert.equal(c.canChange(row,'alice',created+86400000),false);
assert.equal(c.canChange(row,'bob',created+1000),false);
assert.equal(c.canChange({...row,User:'bob'},'bob',created+1000),false,'immutable Added_User wins over dropdown');
assert.equal(c.canChange({...row,Deleted:true},'alice',created+1000),false);
assert.equal(c.canChange({...row,Added_Time:''},'alice',created+1000),false);
assert.equal(c.canChange(row,'alice',created-1),false);
assert.equal(c.canChange(row,'alice@zohocreator.com',created+1000),true);
assert.equal(c.canChange({...row,Added_User:'Alice Smith',User:'alice@wbdevelopment.com'},'alice@wbdevelopment.com',created+1000),true,'Creator User field restores email ownership when Added User is a display name');
assert.equal(c.timestamp('15-Sep-2026 08:29:10 AM'),Date.parse('2026-09-15T08:29:10-05:00'));
assert.equal(c.timestamp('15-Sep-2026 08:29 PM'),Date.parse('2026-09-15T20:29:00-05:00'));
assert.equal(c.timestamp('09/15/2026 01:40:27 PM'),Date.parse('2026-09-15T13:40:27-05:00'),'production Comment_Log Added Time format');
const productionRow={Added_User:'wbdevelopment',User:'wbdevelopment',Added_Time:'09/15/2026 01:40:27 PM',Author_Name:'Robby Belliveau',Deleted:false};
assert.equal(c.canChange(productionRow,'wbdevelopment',Date.parse('2026-09-15T13:41:00-05:00')),true,'production admin identity is eligible during the edit window');
assert.equal(c.canChange(productionRow,'rbelliveau@wbdevelopment.com',Date.parse('2026-09-15T13:41:00-05:00'),['wbdevelopment']),true,'Robby admin alias maps only to Creator\'s stored admin identity');
assert.equal(c.canChange(productionRow,'another-admin@wbdevelopment.com',Date.parse('2026-09-15T13:41:00-05:00')),false,'other administrators do not inherit the exception');
