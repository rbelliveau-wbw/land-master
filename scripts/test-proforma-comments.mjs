import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={module:{exports:{}},Intl,Date};
vm.runInNewContext(fs.readFileSync('widgets/proforma-manager/src/app/comments.js','utf8'),context);
const c=context.module.exports.PFComments;
const row={Added_User:'alice',User:'alice',Added_Time:'15-Sep-2026 08:00:00',Author_Name:'Alice Bell',Deleted:false};
const created=Date.parse('2026-09-15T13:00:00Z');
assert.equal(c.timestamp(row.Added_Time),created);
assert.equal(c.timestamp('15-Jan-2026 08:00:00'),Date.parse('2026-01-15T14:00:00Z'));
assert.equal(c.author(row,[]),'Alice Bell');
assert.equal(c.author({...row,Author_Name:''},[]),'alice');
assert.equal(c.author(row,[{email:'alice',Full_Name:'Alice Updated'}]),'Alice Updated');
assert.equal(c.canChange(row,'alice',created+86400000-1),true);
assert.equal(c.canChange(row,'alice',created+86400000),false);
assert.equal(c.canChange(row,'bob',created+1000),false);
assert.equal(c.canChange({...row,User:'bob'},'bob',created+1000),false,'immutable Added_User wins over dropdown');
assert.equal(c.canChange({...row,Deleted:true},'alice',created+1000),false);
assert.equal(c.canChange({...row,Added_Time:''},'alice',created+1000),false);
assert.equal(c.canChange(row,'alice',created-1),false);
assert.equal(c.canChange(row,'alice@zohocreator.com',created+1000),true);
assert.equal(c.canChange({...row,Added_User:'Alice Smith',User:'alice@wbdevelopment.com'},'alice@wbdevelopment.com',created+1000),true,'Creator User field restores email ownership when Added User is a display name');
assert.equal(c.timestamp('15-Sep-2026 08:29:10 AM'),Date.parse('2026-09-15T08:29:10-05:00'));
assert.equal(c.timestamp('15-Sep-2026 08:29 PM'),Date.parse('2026-09-15T20:29:00-05:00'));
assert.equal(c.timestamp('09/15/2026 01:40:27 PM'),Date.parse('2026-09-15T13:40:27-05:00'),'production Comment_Log Added Time format');
const productionRow={Added_User:'wbdevelopment',User:'wbdevelopment',Added_Time:'09/15/2026 01:40:27 PM',Author_Name:'Robby Belliveau',Deleted:false};
assert.equal(c.canChange(productionRow,'wbdevelopment',Date.parse('2026-09-15T13:41:00-05:00')),true,'production admin identity is eligible during the edit window');
assert.equal(c.canChange(productionRow,'rbelliveau@wbdevelopment.com',Date.parse('2026-09-15T13:41:00-05:00'),['wbdevelopment']),true,'Robby admin alias maps only to Creator\'s stored admin identity');
assert.equal(c.canChange(productionRow,'another-admin@wbdevelopment.com',Date.parse('2026-09-15T13:41:00-05:00')),false,'other administrators do not inherit the exception');
const rich=c.markdown('**Bold** *italic* ~~old~~ `code`\n> quote\n- item\n[Site](https://example.com)');
for(const tag of ['strong','em','s','code','blockquote','a'])assert.match(rich,new RegExp('<'+tag+'[ >]'));
const xss=c.markdown('<img src=x onerror=alert(1)>\n[bad](javascript:alert(1))\nhttps://x.com/"onclick="oops');
assert.ok(!xss.includes('<img'));
assert.ok(!xss.includes('href="javascript:'));
assert.ok(!xss.includes('"onclick="'));
assert.equal(c.color('alice'),c.color('ALICE'));
const source=fs.readFileSync('widgets/proforma-manager/src/app/widget.html','utf8');
assert.match(source,/comments:1/);
assert.match(source,/id="recCommentsBtn"/);
assert.match(source,/id="commentModal"/);
assert.doesNotMatch(source,/data-recview="comments"/);
assert.match(source,/refreshPfCommentBadge\(pfId\)/);
assert.match(source,/rec-nav-wrap/);
assert.ok(source.indexOf('id="recSwitch"') < source.indexOf('id="recCommentsBtn"'),'header Comments control follows the record tabs');
assert.match(source,/\.rec-comments-btn\{[^}]*width:49\.5px[^}]*height:49\.5px/,'header Comments control is 10% larger');
assert.match(source,/if\(grpEd\) grpEd\.style\.display="none";/,'editor heading is replaced by persistent record context');
assert.match(source,/if\(grpDash\) grpDash\.style\.display="";/,'record identity stays visible on every record tab');
assert.match(source,/data-act="comments" data-actid/,'every saved Pro Forma row exposes the Comments modal action');
assert.match(source,/act==="comments"\) openPfComments\(id,b\)/,'list Comments action opens the shared modal');
assert.match(source,/function loadPfCommentSummaries\(\)/,'list comment summaries load once');
assert.match(source,/\+pfListCommentAction\(r\)/,'list action renders its Comment Log badge');
assert.match(source,/\.pf-row-comments\.has-recent/,'list action receives the same recent-activity state');
assert.match(source,/loadPfCommentSummaries\(\);/,'list requests comment summaries after rendering');
assert.match(source,/z-index:10060/);
assert.doesNotMatch(source,/record\.Name\+" — Comments"/);
assert.match(source,/commentWrite\("updateRecord"/);
assert.match(source,/rbelliveau@wbdevelopment\.com"\?\["wbdevelopment"\]:\[\]/);
assert.match(source,/\.pc-actions\{opacity:1!important\}/);
assert.ok(!/function commentWrite[\s\S]*?function openPfComments/.exec(source)[0].includes('skip_workflow'));
const commentSource=fs.readFileSync('widgets/proforma-manager/src/app/comments.js','utf8');
assert.match(commentSource,/onRows/);
assert.doesNotMatch(commentSource,/data-pc="copy"/);
assert.doesNotMatch(commentSource,/pc-search|data-pc="refresh"/);
assert.match(commentSource,/pc-inline-editor/);
assert.match(commentSource,/inline-cancel/);
const workflow=fs.readFileSync('creator/workflows/Validate_Comment_Log.dg','utf8');
for(const rule of ['existingComment.Added_User != zoho.loginuser','existingComment.Added_Time.addHour(24) <= zoho.currenttime','existingComment.Deleted == true','input.Comment = "Deleted by user"','authorAccess.Full_Name','input.Author_Name = zoho.loginuser'])assert.ok(workflow.includes(rule));
console.log('Comment authors, 24-hour boundaries, timezone, safe formatting and SDK contract verified.');
