import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={module:{exports:{}},Intl,Date};
vm.runInNewContext(fs.readFileSync('widgets/proforma-manager/src/app/comments.js','utf8'),context);
const c=context.module.exports.PFComments;
const row={Added_User:'alice',User:'alice',Added_Time:'15-Sep-2026 08:00:00',Author_Name:'Alice Bell',Deleted:false};
const created=Date.parse('2026-09-15T13:00:00Z');
assert.equal(c.timestamp(row.Added_Time),created);
assert.equal(c.timestamp('15-Jan-2026 08:00:00'),Date.parse('2026-01-15T14:00:00Z'));
assert.equal(c.author(row,[]),'Alice Bell');
assert.equal(c.author({...row,Author_Name:''},[]),'alice');
assert.equal(c.author(row,[{email:'alice',Full_Name:'Alice Updated'}]),'Alice Updated');
assert.equal(c.canChange(row,'alice',created+86400000-1),true);
assert.equal(c.canChange(row,'alice',created+86400000),false);
assert.equal(c.canChange(row,'bob',created+1000),false);
assert.equal(c.canChange({...row,User:'bob'},'bob',created+1000),false,'immutable Added_User wins over dropdown');
assert.equal(c.canChange({...row,Deleted:true},'alice',created+1000),false);
assert.equal(c.canChange({...row,Added_Time:''},'alice',created+1000),false);
assert.equal(c.canChange(row,'alice',created-1),false);
assert.equal(c.canChange(row,'alice@zohocreator.com',created+1000),true);
const rich=c.markdown('**Bold** *italic* ~~old~~ `code`\n> quote\n- item\n[Site](https://example.com)');
for(const tag of ['strong','em','s','code','blockquote','a'])assert.match(rich,new RegExp('<'+tag+'[ >]'));
const xss=c.markdown('<img src=x onerror=alert(1)>\n[bad](javascript:alert(1))\nhttps://x.com/"onclick="oops');
assert.ok(!xss.includes('<img'));
assert.ok(!xss.includes('href="javascript:'));
assert.ok(!xss.includes('"onclick="'));
assert.equal(c.color('alice'),c.color('ALICE'));
const source=fs.readFileSync('widgets/proforma-manager/src/app/widget.html','utf8');
assert.match(source,/comments:1/);
assert.match(source,/data-recview="comments"/);
assert.match(source,/commentWrite\("updateRecord"/);
assert.ok(!/function commentWrite[\s\S]*?function openPfComments/.exec(source)[0].includes('skip_workflow'));
const workflow=fs.readFileSync('creator/workflows/Validate_Comment_Log.dg','utf8');
for(const rule of ['existingComment.Added_User != zoho.loginuser','existingComment.Added_Time.addHour(24) <= zoho.currenttime','existingComment.Deleted == true','input.Comment = "Deleted by user"','authorAccess.Full_Name','input.Author_Name = zoho.loginuser'])assert.ok(workflow.includes(rule));
console.log('Comment authors, 24-hour boundaries, timezone, safe formatting and SDK contract verified.');
