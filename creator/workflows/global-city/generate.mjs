import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const folder=path.dirname(fileURLToPath(import.meta.url));
const manifest=JSON.parse(fs.readFileSync(path.join(folder,'consumers.json'),'utf8'));
const check=process.argv.includes('--check');
const outputs=new Map();
const push=(lines,...values)=>lines.push(...values);
function collect(lines,target,field,selection,indent=''){
  push(lines,indent+'if('+field+' != null)',indent+'{');
  if(selection==='multi')push(lines,indent+' for each sharedCityChoice in '+field,indent+' {',indent+'  '+target+'.add(sharedCityChoice);',indent+' }');
  else push(lines,indent+' if('+field+' != "")',indent+' {',indent+'  '+target+'.add('+field+');',indent+' }');
  push(lines,indent+'}');
}
function sameSet(lines,left,right,prefix,indent=''){
  for(const [name,source] of [[prefix+'Left',left],[prefix+'Right',right]]){
    push(lines,indent+name+' = List();',indent+'for each sharedCitySetValue in '+source,indent+'{',indent+' if(!'+name+'.contains(sharedCitySetValue))',indent+' {',indent+'  '+name+'.add(sharedCitySetValue);',indent+' }',indent+'}');
  }
  push(lines,indent+prefix+'Same = '+prefix+'Left.size() == '+prefix+'Right.size();',indent+'for each sharedCitySetValue in '+prefix+'Left',indent+'{',indent+' if(!'+prefix+'Right.contains(sharedCitySetValue))',indent+' {',indent+'  '+prefix+'Same = false;',indent+' }',indent+'}');
}
function preamble(consumer){
  const lines=['// Generated by global-city/generate.mjs. Keep policy in globalCityPolicy.',
    '// '+consumer.form+' / City: '+consumer.mode+' '+consumer.selection+' consumer; existing native storage/mandatory rules stay unchanged.',
    'sharedCityRequested = List();'];
  collect(lines,'sharedCityRequested','input.City',consumer.selection);
  push(lines,'sharedCitySavedValues = List();','sharedCityAllowRetained = false;');
  if(consumer.mode!=='persisted'){
    push(lines,'// Transient/filter input is not a saved-record legacy exemption.');
    return lines;
  }
  push(lines,'if(input.ID != null)','{',' sharedCityStored = '+consumer.form+'[ID == input.ID];',' if(sharedCityStored.count() > 0 && sharedCityStored.ID == input.ID)',' {');
  collect(lines,'sharedCitySavedValues','sharedCityStored.City',consumer.selection,'  ');
  sameSet(lines,'sharedCityRequested','sharedCitySavedValues','sharedCityValues','  ');
  push(lines,'  sharedCitySameScope = true;');
  for(const spec of consumer.retention_scope){
    const [field,kind]=spec.split(':');
    if(kind==='set'){
      for(const [name,source] of [['sharedCityInputScope','input.'+field],['sharedCitySavedScope','sharedCityStored.'+field]]){
        push(lines,'  '+name+' = List();','  if('+source+' != null)','  {','   for each sharedCityScopeId in '+source,'   {','    '+name+'.add(sharedCityScopeId.toString());','   }','  }');
      }
      sameSet(lines,'sharedCityInputScope','sharedCitySavedScope','sharedCityScope','  ');
      push(lines,'  if(sharedCityScopeSame != true)','  {','   sharedCitySameScope = false;','  }');
    }else if(kind==='legal-default'){
      push(lines,'  sharedCityCurrentModule = ifnull(input.'+field+',"").toString();','  sharedCitySavedModule = ifnull(sharedCityStored.'+field+',"").toString();','  if(sharedCityCurrentModule == "")','  {','   sharedCityCurrentModule = "Legal";','  }','  if(sharedCitySavedModule == "")','  {','   sharedCitySavedModule = "Legal";','  }','  if(sharedCityCurrentModule != sharedCitySavedModule)','  {','   sharedCitySameScope = false;','  }');
    }else{
      push(lines,'  if(ifnull(input.'+field+',"").toString() != ifnull(sharedCityStored.'+field+',"").toString())','  {','   sharedCitySameScope = false;','  }');
    }
  }
  push(lines,'  sharedCityAllowRetained = sharedCityValuesSame && sharedCitySameScope;',' }','}');
  return lines;
}
for(const consumer of manifest.consumers){
  const validation=preamble(consumer);
  push(validation,'sharedCityPolicy = thisapp.globalCityPolicy(sharedCityRequested,sharedCitySavedValues,sharedCityAllowRetained);','if(sharedCityPolicy.get("ok") != true)','{',' alert sharedCityPolicy.get("message");',' cancel submit;','}');
  outputs.set(consumer.on_validate,validation.join('\n')+'\n');
  const load=preamble(consumer);
  push(load,'sharedCityPolicy = thisapp.globalCityPolicy(sharedCityRequested,sharedCitySavedValues,sharedCityAllowRetained);','sharedCityChoices = sharedCityPolicy.get("choices");','// Preserve the mounted selection if the global authority is unavailable.','// The server guard still rejects a save until that configuration is repaired.','if(sharedCityChoices.size() > 0)','{','clear City;','City:ui.add(sharedCityChoices);');
  if(consumer.selection==='multi'){
    push(load,'sharedCitySelection = List();','for each sharedCityCurrent in sharedCityRequested','{',' if(sharedCityChoices.contains(sharedCityCurrent))',' {','  sharedCitySelection.add(sharedCityCurrent);',' }','}','input.City = sharedCitySelection;');
  }else{
    push(load,'input.City = null;','for each sharedCityCurrent in sharedCityRequested','{',' if(sharedCityChoices.contains(sharedCityCurrent))',' {','  input.City = sharedCityCurrent;',' }','}');
  }
  push(load,'}');
  outputs.set(consumer.on_load,load.join('\n')+'\n');
}
// The current mirror includes later native guards. Keep it authoritative and
// never regenerate a historical body or append the City binding twice.
const current=fs.readFileSync(path.join(folder,'../Field_Validations_Contrac.dg'),'utf8');
const binding=outputs.get('bindings/Contract.on-validate.dg');
const marker='// Generated by global-city/generate.mjs. Keep policy in globalCityPolicy.';
const existingStart=current.indexOf(marker);
if(existingStart>=0){
  if(current.slice(existingStart).trimEnd()!==binding.trimEnd())throw Error('Current Contract City binding changed; inspect before regenerating.');
  outputs.set('Contract.Field_Validations_Contrac.merged.dg',current.trimEnd()+'\n');
}else{
  outputs.set('Contract.Field_Validations_Contrac.merged.dg',current.trimEnd()+'\n\n'+binding);
}
for(const [relative,content] of outputs){
  const target=path.join(folder,relative);
  if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content)throw Error('Regenerate '+relative);}
  else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,content);}
}
console.log((check?'Verified':'Generated')+' 20 thin native bindings and the Contract validation integration copy.');
